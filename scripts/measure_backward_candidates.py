"""How many one-step backward candidates are dead ends, and how often does a uniform P_B fail?

Reads a run's sample.jsonl (molecules produced by a trained forward policy) and reports, for
early and late training steps:

* |C(s)|: one-step reverse candidates per product state, and how often the *generated* edge
  is not regenerated by the one-step generator (observed-missing);
* tied candidates: edges a state offers that the backward head cannot tell apart, because
  they share everything it sees -- action type, reaction and removed synthon -- and differ
  only in the parent. A tie whose members differ in recoverability is one the head can never
  learn to resolve, however long REINFORCE runs;
* dead candidates among the reverse steps available from each final molecule, split into
  structural dead ends (the parent cannot be built even with generous limits) and budget dead
  ends (buildable, but not within the forward MDP's reaction/synthon limits);
* p_succ: probability that a backward walk with a uniform P_B reaches the empty state within
  the forward limits. 1 - p_succ is the signal available to a validity reward, and p_succ is
  the factor by which a leaky P_B distorts the distribution TB learns to sample from;
* agreement with the existing recursive search (`_dfs`);
* cost of one `one_step` call.

Usage: python scripts/measure_backward_candidates.py --samples ~/runs/ref/qed-200/sample.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
import time
from collections import Counter
from functools import lru_cache
from pathlib import Path

import numpy as np

from IFT6760.envs.env import SynthesisEnv

LOOSE = 8


def edge_key(env: SynthesisEnv, edge) -> tuple:
    """Identify an edge without the (unlogged) library index: type, reaction, synthon, parent."""
    action, parent = edge
    synthon = None
    if action.library_name is not None:
        synthon = env.synthons[action.library_name].smiles[action.synthon_index]
    return (action.action_type.name, action.reaction, synthon, parent)


def head_key(edge) -> tuple:
    """Everything the backward head sees about an edge: the parent is deliberately absent.

    Two candidates of the same state with equal `head_key` receive equal logits under every
    parameter setting, so P_B can never prefer one over the other.
    """
    action, _ = edge
    return (
        action.action_type.name,
        action.reaction,
        action.library_name,
        action.synthon_index,
    )


def observed_key(step: dict) -> tuple:
    return (
        step["action_type"],
        step["reaction"],
        step.get("synthon_smiles"),
        step["state"],
    )


class Walker:
    """Exact backward walk statistics over the one-step candidate graph."""

    def __init__(self, env: SynthesisEnv, min_r, max_r, min_s, max_s):
        self.env, self.limits = env, (min_r, max_r, min_s, max_s)
        self.analyzer = env.retro_analyzer
        self.walk = lru_cache(maxsize=None)(self._walk)

    def _step_counts(self, action, reactions, synthons):
        return (
            reactions + (0 if action.action_type.is_first else 1),
            synthons + (0 if action.action_type.is_unirxn else 1),
        )

    def edge_outcome(self, edge, reactions, synthons, limits):
        """(uniform success probability, buildable) after taking `edge` from the counters."""
        _, max_r, _, max_s = limits
        action, parent = edge
        r, s = self._step_counts(action, reactions, synthons)
        if r > max_r or s > max_s:
            return 0.0, False
        if parent == "":
            ok = r >= limits[0] and s >= limits[2]
            return float(ok), ok
        return self.walk(parent, r, s, limits)

    def _walk(self, smiles, reactions, synthons, limits):
        edges = self.analyzer.one_step(smiles)
        if not edges:
            return 0.0, False
        outcomes = [self.edge_outcome(e, reactions, synthons, limits) for e in edges]
        return sum(p for p, _ in outcomes) / len(edges), any(b for _, b in outcomes)

    def strict(self, edge, state=(0, 0)):
        return self.edge_outcome(edge, *state, self.limits)

    def loose(self, edge, state=(0, 0)):
        return self.edge_outcome(edge, *state, (0, LOOSE, 0, LOOSE))


def load_phase(path: Path, lo: int, hi: int, valid_only=True):
    rows = []
    with path.open() as handle:
        for line in handle:
            row = json.loads(line)
            if lo <= row["step"] <= hi and (row["valid"] or not valid_only):
                rows.append(row)
    return rows


def pct(x, n):
    return f"{100 * x / max(n, 1):.1f}%"


def analyze(env, walker, rows, max_mols, seed):
    rng = random.Random(seed)
    seen, picked = set(), []
    for row in rows:
        if row["final_smiles"] not in seen:
            seen.add(row["final_smiles"])
            picked.append(row)
    rng.shuffle(picked)
    picked = picked[:max_mols]

    analyzer = env.retro_analyzer
    sizes, missing, n_states = Counter(), 0, 0
    missing_by_type: Counter = Counter()
    missing_examples: list[dict] = []
    tied_states = tied_edges = 0
    by_depth: dict[int, list[int]] = {}
    times = []
    for row in picked:
        for depth, step in enumerate(row["traj"], start=1):
            smiles = step["product_smiles"]
            start = time.perf_counter()
            edges = analyzer.worker.one_step(smiles)  # uncached call, for timing
            times.append(time.perf_counter() - start)
            keys = {edge_key(env, e) for e in edges}
            n_states += 1
            sizes[len(edges)] += 1
            by_depth.setdefault(depth, []).append(len(edges))
            groups = Counter(head_key(e) for e in edges)
            ties = sum(n for n in groups.values() if n > 1)
            tied_states += ties > 0
            tied_edges += ties
            if observed_key(step) not in keys:
                missing += 1
                missing_by_type[step["action_type"]] += 1
                if len(missing_examples) < 5:
                    missing_examples.append(
                        {
                            "product_smiles": smiles,
                            "action_type": step["action_type"],
                            "reaction": step["reaction"],
                            "synthon_smiles": step.get("synthon_smiles"),
                            "parent": step["state"],
                            "candidates": [str(k) for k in sorted(map(str, keys))],
                        }
                    )

    cand = dead = dead_struct = dead_budget = 0
    tie_groups = consequential_tie_groups = 0
    p_succ, dead_mass = [], []
    agree = subset = superset = 0
    for row in picked:
        final = row["final_smiles"]
        edges = analyzer.one_step(final)
        outcomes = [(walker.strict(e), walker.loose(e)) for e in edges]
        cand += len(edges)
        buildable_by_key: dict[tuple, set[bool]] = {}
        for edge, ((_, strict_ok), _) in zip(edges, outcomes, strict=True):
            buildable_by_key.setdefault(head_key(edge), set()).add(strict_ok)
        for key, flags in buildable_by_key.items():
            members = sum(head_key(e) == key for e in edges)
            if members > 1:
                tie_groups += 1
                consequential_tie_groups += len(flags) > 1
        for (_, strict_ok), (_, loose_ok) in outcomes:
            dead += not strict_ok
            dead_struct += not loose_ok
            dead_budget += loose_ok and not strict_ok
        p = sum(s[0] for s, _ in outcomes) / len(edges) if edges else 0.0
        p_succ.append(p)
        dead_mass.append(1.0 - p)
        ours = {e for e, (s, _) in zip(edges, outcomes, strict=True) if s[1]}
        dfs = {route[0] for route in analyzer.run(final)}
        agree += dfs == ours
        subset += dfs <= ours
        superset += ours <= dfs

    p = np.array(p_succ)
    n = len(picked)
    return {
        "molecules": n,
        "states": n_states,
        "candidates_per_state": {str(k): v for k, v in sorted(sizes.items())},
        "mean_candidates_by_depth": {
            d: float(np.mean(v)) for d, v in sorted(by_depth.items())
        },
        "observed_edge_missing": missing,
        "observed_edge_missing_rate": missing / max(n_states, 1),
        "observed_edge_missing_by_type": dict(missing_by_type),
        "observed_edge_missing_examples": missing_examples,
        "tied_states": tied_states,
        "tied_edges": tied_edges,
        "tie_groups_at_final": tie_groups,
        "consequential_tie_groups_at_final": consequential_tie_groups,
        "final_state_candidates": cand,
        "dead_candidates": dead,
        "dead_structural": dead_struct,
        "dead_budget": dead_budget,
        "p_succ_mean": float(p.mean()),
        "p_succ_min": float(p.min()),
        "molecules_with_p_succ_below_1": int((p < 1 - 1e-9).sum()),
        "molecules_with_p_succ_zero": int((p < 1e-9).sum()),
        "dfs_first_edges_equal_ours": agree,
        "dfs_first_edges_subset_of_ours": subset,
        "ours_subset_of_dfs": superset,
        "one_step_ms_mean": 1000 * float(np.mean(times)),
        "one_step_ms_median": 1000 * float(np.median(times)),
        "one_step_ms_p95": 1000 * float(np.percentile(times, 95)),
    }


def report(name, r):
    n, c = r["molecules"], r["final_state_candidates"]
    print(f"\n=== {name}: {n} unique molecules, {r['states']} product states")
    print("  candidates per state:", r["candidates_per_state"])
    print(
        "  mean |C| by step depth:",
        {d: round(v, 2) for d, v in r["mean_candidates_by_depth"].items()},
    )
    print(
        f"  observed edge not regenerated: {r['observed_edge_missing']}/{r['states']} "
        f"({100 * r['observed_edge_missing_rate']:.2f}%) by type: "
        f"{r['observed_edge_missing_by_type'] or '-'}"
    )
    for example in r["observed_edge_missing_examples"]:
        print(f"    MISSING {example}")
    print(
        f"  tied candidates (head cannot tell them apart): {r['tied_edges']} edges in "
        f"{r['tied_states']}/{r['states']} states; at final molecules {r['tie_groups_at_final']} "
        f"tie groups, {r['consequential_tie_groups_at_final']} of them mixing recoverable "
        f"with dead parents"
    )
    print(
        f"  candidates at final molecules: {c}; dead {r['dead_candidates']} ({pct(r['dead_candidates'], c)}) = "
        f"structural {r['dead_structural']} + budget {r['dead_budget']}"
    )
    print(
        f"  uniform-P_B success p_succ: mean {r['p_succ_mean']:.4f}, min {r['p_succ_min']:.3f}; "
        f"{r['molecules_with_p_succ_below_1']}/{n} molecules below 1 ({r['molecules_with_p_succ_zero']} at 0)"
    )
    print(
        f"  recursive search first edges: equal {r['dfs_first_edges_equal_ours']}/{n}, "
        f"subset-of-ours {r['dfs_first_edges_subset_of_ours']}/{n}, ours-subset-of-theirs {r['ours_subset_of_dfs']}/{n}"
    )
    print(
        f"  one_step cost: mean {r['one_step_ms_mean']:.2f} ms, median {r['one_step_ms_median']:.2f}, "
        f"p95 {r['one_step_ms_p95']:.2f}"
    )


def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--samples", type=Path, required=True, help="sample.jsonl of a training run"
    )
    ap.add_argument("--env-dir", type=Path, default=Path("data/envs/example_5k"))
    ap.add_argument("--early", type=int, nargs=2, default=[1, 5], metavar=("LO", "HI"))
    ap.add_argument("--late", type=int, nargs=2, default=[196, 200], metavar=("LO", "HI"))
    ap.add_argument("--max-mols", type=int, default=300)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--min-synthons", type=int, default=2)
    ap.add_argument("--max-synthons", type=int, default=3)
    ap.add_argument("--min-reactions", type=int, default=1)
    ap.add_argument("--max-reactions", type=int, default=3)
    ap.add_argument("--out", type=Path, help="write the numbers as JSON")
    args = ap.parse_args(argv)

    env = SynthesisEnv(
        args.env_dir,
        max_reactions=args.max_reactions,
        min_synthons=args.min_synthons,
        max_synthons=args.max_synthons,
        min_reactions=args.min_reactions,
    )
    walker = Walker(
        env, args.min_reactions, args.max_reactions, args.min_synthons, args.max_synthons
    )
    results = {}
    for name, (lo, hi) in (("early", args.early), ("late", args.late)):
        rows = load_phase(args.samples, lo, hi)
        if not rows:
            print(f"no valid rows for steps {lo}-{hi}")
            continue
        results[name] = analyze(env, walker, rows, args.max_mols, args.seed)
        report(f"{name} (steps {lo}-{hi})", results[name])
    env.close()
    if args.out:
        args.out.write_text(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
